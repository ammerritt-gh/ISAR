def test_objective_was_a_tracked_acoustic_map_with_the_clipping_band(ap6):
    obj = ap6["objective"]
    assert obj["branch"] == "acoustic"
    assert obj["selector"] == "tracked_branch"
    assert obj["path_len"] == 21
    # The acoustic default band ends at 7 meV — the ceiling this whole repair is about.
    assert obj["energy_search_meV"] == [-2.0, 7.0]


def test_terminal_was_honest_incomplete_branch_ambiguity(ap6):
    assert ap6["terminal"]["state"] == "incomplete"
    assert ap6["terminal"]["reasons"] == [_TERMINAL_REASON]


def test_frontier_state_explains_why_no_same_q_fallback_fired(ap6):
    f = ap6["frontier_per_q"]
    # Index 18 (H=2.9): ambiguous, identity undecided (P<0.85), yet identity_saturated — this is the
    # brake that made same-q identity work stop being authorised, while only two productions had run
    # and neither the exposure nor the strategy ceiling was reached.
    p18 = f["18"]
    assert p18["track_state"] == "ambiguous"
    assert p18["identity_saturated"] is True
    assert p18["local_identity_clear"] is False
    assert p18["target_probability"] == pytest.approx(0.7069, abs=1e-3)
    assert p18["target_probability"] < 0.85
    assert p18["n_production"] == 2
    assert p18["exposure_saturated"] is False
    assert p18["strategy_ceiling_reached"] is False
    # Indices 19/20 (H=2.95/3.0): blocked — behind an unresolved frontier, not independently actionable.
    for idx in ("19", "20"):
        assert f[idx]["track_state"] == "blocked"


def test_every_emitted_frontier_window_was_clipped_at_the_7meV_ceiling(ap6):
    windows = ap6["emitted_windows_at_frontier"]
    assert windows, "expected at least one emitted window at the frontier q"
    # The rival mode needed to settle acoustic identity at H=2.9 sits at ~7.115 meV. Every scan the
    # driver emitted at the frontier stopped at e_hi = 7.0 — the rival was outside every window.
    assert all(w["e_hi"] == 7.0 for w in windows)
    assert all(w["e_lo"] == -2.0 for w in windows)
    assert max(w["e_hi"] for w in windows) < 7.115


