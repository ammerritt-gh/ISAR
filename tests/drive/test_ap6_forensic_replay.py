def _identity_saturated_updates() -> list[dict]:
    """Three comparable revisions whose exposure doubled while the identity metrics stalled.

    This is exactly the shape ``GridQ.identity_saturated`` reads: exposure ratio >= 2 with the target
    probability and identity entropy improving by less than the floor, so the property returns True —
    reproducing index 18's recorded ``identity_saturated`` without needing the full update history.
    """
    return [
        {"effective_exposure": 1.0e7, "target_probability": 0.7069, "identity_entropy": 0.5972},
        {"effective_exposure": 2.0e7, "target_probability": 0.7069, "identity_entropy": 0.5972},
        {"effective_exposure": 4.0e7, "target_probability": 0.7069, "identity_entropy": 0.5972},
    ]


def _ap6_frontier_grid(*, saturated_at_18: bool = True) -> list[GridQ]:
    """A 21-point grid whose blocked frontier reproduces AP6's terminal per-q state."""
    grid: list[GridQ] = []
    for index in range(21):
        point = GridQ(index=index, hkl=(2.0 + 0.05 * index, 0.0, 0.0), q=0.05 * index,
                      tolerance=0.5, max_production_batches=12, evidence_master={})
        if index <= 17:
            point.track_state = "confirmed"
            point.local_identity_clear = True
            point.n_production = 1
        elif index == 18:
            point.track_state = "ambiguous"
            point.local_identity_clear = False
            point.target_probability = 0.7069
            point.identity_entropy = 0.5972
            point.n_production = 2
            if saturated_at_18:
                point.identity_updates = _identity_saturated_updates()
        else:  # 19, 20 — blocked behind the unresolved frontier
            point.track_state = "blocked"
            point.local_identity_clear = False
            point.n_production = 0 if index == 19 else 2
        grid.append(point)
    return grid


def _continue_decision(grid: list[GridQ]) -> StopDecision:
    per_q = [{"index": p.index, "hkl": list(p.hkl), "assessment_state": "ambiguous"} for p in grid]
    return StopDecision("continue", [], per_q)


def test_frontier_saturation_is_reproduced_by_the_real_property(ap6):
    grid = _ap6_frontier_grid(saturated_at_18=True)
    assert grid[18].identity_saturated is True
    # The reconstruction must match AP6 on exactly the fields same_q_identity_work_remains consumes,
    # so the terminal is reproduced for the right reason and not by an accidental default. AP6 recorded
    # both False at index 18; the predicate would keep same-q work available if either were True.
    recorded = ap6["frontier_per_q"]["18"]
    assert recorded["exposure_saturated"] is False
    assert recorded["strategy_ceiling_reached"] is False
    assert grid[18].exposure_saturated is False
    assert grid[18].same_q_ceiling_reached is False
    # And with same-q work removed at 18 plus blocked 19/20, no blocked point remains actionable.
    for index in (18, 19, 20):
        assert grid[index].same_q_identity_work_remains is False


def test_saturation_is_rule_driven_not_incidental_to_the_handcrafted_updates():
    """The saturated case must be saturated *because* exposure grew while the metrics stalled — not
    merely because the rows happen to be equal. Shrinking the exposure ratio below the floor must flip
    identity_saturated back to False, and with it restore same-q identity work at the frontier."""
    grid = _ap6_frontier_grid(saturated_at_18=True)
    under_exposed = [dict(update) for update in _identity_saturated_updates()]
    for update in under_exposed:                       # collapse the exposure growth below the floor
        update["effective_exposure"] = 1.0e7
    grid[18].identity_updates = under_exposed
    assert grid[18].identity_saturated is False
    assert grid[18].same_q_identity_work_remains is True


def test_no_proposal_at_this_frontier_is_an_honest_incomplete_not_a_controller_fault():
    grid = _ap6_frontier_grid(saturated_at_18=True)
    objective = SimpleNamespace(target_selector="tracked_branch")
    decision = _blocked_frontier_decision(objective, grid, _continue_decision(grid))
    # AP6's exact terminal, produced by the real function from a proposal-less frontier.
    assert decision.state == "incomplete"
    assert decision.reasons == [_TERMINAL_REASON]


def test_the_same_frontier_with_same_q_work_remaining_would_be_a_controller_fault():
    """The two-defect distinction, locked. Had index 18 *not* been identity_saturated, same-q identity
    work would still be authorised and a no-proposal terminal would be a controller fault — proving
    AP6's honest incomplete depended specifically on the saturation brake, not on the endpoint alone."""
    grid = _ap6_frontier_grid(saturated_at_18=False)
    assert grid[18].same_q_identity_work_remains is True
    objective = SimpleNamespace(target_selector="tracked_branch")
    with pytest.raises(ControllerInvariantError):
        _blocked_frontier_decision(objective, grid, _continue_decision(grid))


