"""PR0 forensic replay of the AP6_Failed acoustic campaign — no behavior change.

AP6 is the real failed campaign the action-inventory repair exists to fix. It mapped the acoustic
phonon (2,0,0)→(3,0,0) and stopped ``incomplete — branch_ambiguity; frontier_blocked at path
index/indices 18, 19, 20`` with beam time remaining and only two productions at the blocked points.

This module locks *what actually happened* so later PRs are measured against a real baseline, and
proves — through the real predicates, not by trusting the log — that AP6 is the **incomplete
action-space** defect, not the pre-acquisition early-terminal defect:

  * ``evaluate_stop`` returned ``continue``;
  * acquisition returned no proposal at the path-endpoint frontier;
  * ``_blocked_frontier_decision`` terminalised the empty set as an *honest* incomplete because
    ``same_q_identity_work_remains`` was False at every blocked point — it did **not** raise
    ``ControllerInvariantError``.

The compact fixture ``ap6_frontier.json`` is regenerated by ``extract_ap6_frontier.py`` from the
gitignored ``test_workspaces/AP6_Failed/`` workspace; the fast tests below need only the committed
fixture. A slow companion re-derives the same facts from the full frozen workspace when it is present.
"""
