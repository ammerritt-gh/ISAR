def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


@pytest.mark.slow
def test_frozen_workspace_still_matches_the_committed_fixture(ap6):
    if not _WORKSPACE.exists():
        pytest.skip("local AP6_Failed workspace is unavailable")
    # Pin the frozen artifact set explicitly so a future extractor change cannot quietly shrink what
    # the immutability guard covers.
    assert set(ap6["source_hashes"]) == {
        "report/session_log.jsonl", "report/results.csv", "card.state.json"}
    for rel, expected in ap6["source_hashes"].items():
        actual = _sha256(_WORKSPACE / rel)
        assert actual == expected, f"{rel} changed since the freeze — regenerate the fixture"

    events = []
    with open(_WORKSPACE / "report" / "session_log.jsonl", encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if line:
                events.append(json.loads(line))
    stop = next(o["payload"] for o in reversed(events) if o.get("kind") == "stop")
    assert stop["state"] == "incomplete"
    assert stop["reasons"] == [_TERMINAL_REASON]
